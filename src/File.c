/*
 * HEADER:100:grib:output:1:writes GRIB record (one submessage) to X
 */

/**
 * Writes a GRIB record (one submessage) to a specified file in GRIB2 format.
 * 
 * This option only writes the current field (record/submessage) if the GRIB message 
 * contains multiple fields (records/submessages). If you want to copy the entire 
 * GRIB-2 message, use the -GRIB option. 
 * 
 * ## -grib vs. -grib_out
 * These two options do similar things, they write a grib message to a specified file. 
 * The -grib writes the grib message and -grib_out option takes the decoded grib message, 
 * converts it back into grib2 and then writes it out. Obviously the latter option is much 
 * slower. You only use -grib_out when you have modified the data (grid) values. For example, 
 * you may have set many of the points to undefined in order to the data volume. Since the 
 * data values have changed, you have to use the -grib_out in order to create the smaller 
 * grib file. 
 * 
 * ## Usage
 * -grib file_name
 * 
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 * 
 * @return 0 for success, error code otherwise
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_grib(ARG1) {
    int i;
    struct seq_file *save;

    i = 0;
    if (mode == -1) {
        *local = save = (struct seq_file *) malloc( sizeof(struct seq_file));
        if (save == NULL) fatal_error("grib: memory allocation","");

        if (fopen_file(save, arg1, file_append ? "ab" : "wb") != 0) {
            free(save);
            fatal_error("Could not open %s", arg1);
        }
    }
    else if (mode == -2) {
        save = (struct seq_file *) *local;
        fclose_file(save);
        free(save);
    }
    else if (mode >= 0) {
        save = (struct seq_file *) *local;
        i = wrt_sec(sec[0], sec[1], sec[2], sec[3], sec[4], sec[5], sec[6],
                    sec[7], save);
        if (flush_mode) fflush_file(save);
    }
    return i;
}

/*
 * HEADER:100:persistent:setup:1:makes file X persistent if already opened (default on open), CW2
 *   only useful when wgrib is called as a subroutine, no error if failure
 */

/**
 * Marks an already open file as persistent. 
 * 
 * If a file is marked as persistent, the file will closed when the system terminates the program. 
 * If you run the wgrib2 utility, it makes no difference who closes the files. However, when you 
 * use the C/Fortran API, it makes a major difference. When you write C/Fortran programs that calls 
 * the wgrib2 API, you may want to use the same file thousands of times. It is better to open the 
 * file once rather than thousands of times. 
 * 
 * When opening a file, the default is to mark the file as persistent. 
 * 
 * ## Usage
 * -persistent FILE
 * 
 * FILE must be already opened.
 * 
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 * 
 * @return 0 for success, error code otherwise
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_persistent(ARG1) {
    if (mode == -1) {
        mk_file_persistent(arg1);
    }
    return 0;
}

