/**
 * Writes the grid values to a specified file in binary format  (C: float, Fortran: real)
 * 
 * The default order is WE:SN (see -order option) with f77 header/trailer (see -no_header). 
 * The undefined value is 9.999e20. The file format remains unchanged from wgrib except the 
 * order of grid points can now be specified. 
 * 
 * When the header flag is on (default, or by the option -header), , the header consists of 
 * an integer with the byte count of the data. The size of the integer (4 or 8 bytes) depends 
 * on the native size of the integer. Usually this size is compile time option. This is 
 * different from the f77 header which is generated by -ieee which is always a 4 byte integer. 
 * 
 * When the header flag if off (by the option -no_header), the binary grid points are written 
 * with no header. To read the data, you need to know the size of the grid. 
 * 
 * The default order of the grid point data is WE:SN. The order of the grid point data can be 
 * changed to raw and WE:NS by use of the -order option. 
 * 
 * On most machines, the binary format is either big or little-endian single precision IEEE. 
 * 
 * ## Usage
 * -bin file_name
 * 
 * "-" sends the output to the terminal/stdout (results are unpredicatable in Windows)
 * 
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 * 
 * @return 0 for success, error code otherwise
 * 
 * ## Example 
 * ???
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_bin(ARG1) {
    unsigned int i, j;
    struct seq_file *save;

    if (mode == -1) {
        *local = save = (struct seq_file *) malloc( sizeof(struct seq_file));
        if (save == NULL) fatal_error("bin: memory allocation","");
        if (fopen_file(save, arg1, file_append ? "ab" : "wb") != 0) {
            free(save);
            fatal_error("Could not open %s", arg1);
        }
        decode = 1;
    }
    else if (mode == -2) {
        save = *local;
        fclose_file(save);
        free(save);
    }
    else if (mode >= 0) {
        save = *local;
        if (header) {
            if (ndata > 4294967295U / sizeof(float))
                fatal_error("bin: 4-byte header overflow","");
            i = ndata * sizeof(float);
            j = fwrite_file((void *) &i, sizeof(int), 1, save);
            if (j != 1) fatal_error("bin: write header","");
        }
        j = fwrite_file((void *) data, sizeof(float), ndata, save);
        if (j != ndata) fatal_error_u("bin: error writing grid point written=%u", j);
        if (header) {
            i = ndata * sizeof(float);
            j = fwrite_file((void *) &i, sizeof(int),1, save);
            if (j != 1) fatal_error("bin: write header","");
        }
        if (flush_mode) fflush_file(save);
    }
    return 0;
}

/*
 * HEADER:100:ieee:output:1:write (default:big-endian) IEEE data to X
 */

/**
 * Writes the grid values to a specified file in IEEE format (C: float, Fortran: real)
 *
 * By default, the data are written out in WE:SN order (see -order option) with f77 
 * header/trailer (see -no_header option). The undefined value is 9.999e20. The output 
 * format is unchanged from wgrib except the order can now be specified.
 * 
 * The default is to write a 4 byte header and trailer with the record size in bytes. No 
 * header and trailer are written if the header flag is off by the -no_header option.
 * 
 * The default is write the grid point data in WE:SN order. The ordering of the data can 
 * be changed to raw or WE:NS by the -order option.
 * 
 * The default endian of the header, trailer and data are in big endian order. This can 
 * be changed to little endian by the -little_endian option.
 * 
 * The -ieee option is slower than the -bin option and may not be exact on an ieee machine 
 * because all grid point data is converted from the native format into ieee format by a 
 * software routine.
 *
 * ## Usage
 * -ieee file_name
 *
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 *
 * @return 0 for success, error code otherwise
 *
 * ## Example
 * ???
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_ieee(ARG1) {
    struct seq_file *save;

    if (mode == -1) {
        *local = save = (struct seq_file *) malloc( sizeof(struct seq_file));
        if (save == NULL) fatal_error("ieee: memory allocation","");
        if (fopen_file(save, arg1, file_append ? "ab" : "wb") != 0) {
            free(save);
            fatal_error("Could not open %s", arg1);
        }
        decode = 1;
    }
    else if (mode == -2) {
        save = *local;
        fclose_file(save);
        free(save);
    }
    else if (mode >= 0) {
        save = *local;
        wrtieee(data, ndata, header, save);
        if (flush_mode) fflush_file(save);
    }
    return 0;
}

