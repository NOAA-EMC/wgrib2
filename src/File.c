/*
 * HEADER:100:text:output:1:write text data into X
 */

/**
 * Writes the grid values to a specified file as a text (ascii) file.
 * 
 * The default format (-header) is (per decoded grib message)
 *      NX NY
 *      val-1
 *      val-2
 *      ...
 *      val-(NX*NY)
 * Where NX and NY are the dimension of the grid and val-N is the Nth grid point in 
 * WE:SN order. When the -no_header option is used, the format is 
 * 
 *      val-1
 *      val-2
 *      ...
 *      val-(NX*NY)
 * 
 * The default order of the data is WE:SN which differs from wgrib's order which is 
 * equivalent to the "-order raw" in wgrib2. Another difference is that wgrib's -text 
 * option requires a filename. The undefined value is 9.999e20. The format of the output 
 * is unchanged from wgrib except the order, number of columns and precision can be altered 
 * by the user. 
 * 
 * ## Usage
 * -text_fmt file_name
 * 
 * "-" sends the data to the terminal/stdout
 * 
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 * 
 * @return 0 for success, error code otherwise
 *
 * ## Example
 * ???
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_text(ARG1) {
    unsigned int i;

    if (mode == -1) {
        if ((*local = (void *) ffopen(arg1,file_append ? "a" : "w")) == NULL) 
            fatal_error("Could not open %s", arg1);
        decode = 1;
    }
    else if (mode == -2) {
        ffclose((FILE *) *local);
        // free(*local);
    }
    else if (mode >= 0) {
        if (header == 1) {
            fprintf((FILE *) *local,"%d %d\n", nx, ny);
	    }
        for (i = 0; i < ndata; i++) {
            fprintf((FILE *) *local, text_format, data[i]);
            fprintf((FILE *) *local, ((i+1) % text_column) ? " " : "\n");
        }
        if (flush_mode) fflush((FILE *) *local);
    }
    return 0;
}

/*
 * HEADER:100:spread:output:1:write text - spread sheet format into X (WxText enabled)
 */

/**
 * Writes the grid values to a specified file as a comma separated values (text) which 
 * can be imported into a spread sheet. 
 * 
 *    lon,lat,(VARIABLE DESCRIPTION)
 *    lon-1,lat-1,val-1
 *    lon-2,lat-2,val-2
 *    ...
 *    lon-N,lat-N,val-N
 * 
 * The latitudes and longitudes are only available for supported grids and only the default 
 * WE:SN order is supported. The undefined value is 9.999e20. 
 * 
 * Use the -undefine option to limit the output to specified regions. 
 * 
 * ## Usage
 * -spread file_name
 * 
 * @param ARG1 List of function arguments set by wgrib2's main() function (see @ref ARG1). These arguments 
 * won't be relevant to the average wgrib2 user. See the Usage section above for details about any input 
 * parameters.
 * 
 * @return 0 for success, error code otherwise
 *
 * @note Warning #1: The options -csv, -csv_long, -spread and -text do not support memory files. 
 * You can blame sloth or lack of need. I like to think that text files with grid point values 
 * are are insanely large and shouldn't be saved in memory. 
 * 
 * @note Warning #2: It may be tempting to take a grib file, convert it into a CSV file and then 
 * deal with the CSV file. After all, everybody can read a CSV file. Sure there is a litte 
 * overhead of reading a CSV file but who cares. Suppose you want to read some GFS forecasts files 
 * (20 forecast times, 5 days every 6 hours) at 0.25 x 0.25 degree global resolution. Your CSV file 
 * is going to be about 720 GBs. Suppose that our hard drive can write/read at 70 MB/s. Then we are 
 * talking about 3 hours to write the CSV file and 3 hours to read the CSV file not including CPU time 
 * which will slow down the process. Converting grib into CSV is a viable strategy if the conversion is 
 * limited. You need to restrict the number of fields converted and should consider only converting a 
 * regional domain. Note, I wrote "viable" and not optimal. 
 * 
 * ## Example
 * ???
 * 
 * @author Wesley Ebisuzaki @date 2006
 */
int f_spread(ARG1) {
    unsigned int i;

    if (mode == -1) {
        if ((*local = (void *) ffopen(arg1,file_append ? "a" : "w")) == NULL)
            fatal_error("Could not open %s", arg1);
        WxText = latlon = decode = 1;
    }
    else if (mode == -2) {
        ffclose((FILE *) *local);
    }
    else if (mode >= 0) {
        if (lat == NULL || lon == NULL || data == NULL) {
            fprintf(stderr,"no code to determine lat-lon information, no spread sheet output\n");
            return 0;
        }
        set_mode(0);
        f_var(call_ARG0(inv_out,NULL));
        fprintf((FILE *) *local,"lon,lat,%s",inv_out);
        f_lev(call_ARG0(inv_out,NULL));
        fprintf((FILE *) *local," %s", inv_out);
        f_t(call_ARG0(inv_out,NULL));
        fprintf((FILE *) *local," %s", inv_out);
        f_ftime(call_ARG0(inv_out,NULL));
        fprintf((FILE *) *local," %s\n", inv_out);

        if (WxNum > 0) {
            for (i = 0; i < ndata; i++) {
                if(!UNDEFINED_VAL(data[i])) 
                    fprintf((FILE *) *local,"%lf,%lf,\"%s\"\n",lon[i],lat[i],WxLabel(data[i]));
            }
        }
        else {
            for (i = 0; i < ndata; i++) {
                if(!UNDEFINED_VAL(data[i])) 
                    fprintf((FILE *) *local,"%lf,%lf,%g\n",lon[i],lat[i],data[i]);
            }
        }
        if (flush_mode) fflush((FILE *) *local);
        inv_out[0] = 0;
        set_mode(mode);
    }

    return 0;
}

